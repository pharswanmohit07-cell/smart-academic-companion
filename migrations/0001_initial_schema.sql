-- 0001_initial_schema.sql
--
-- Baseline schema for the Smart Academic Companion on Supabase PostgreSQL.
--
-- The Supabase project already contains auth.users and public.user_profiles
-- (with its RLS policies and the signup trigger). Those are NOT recreated
-- here. This migration creates the application tables and adds the columns
-- that map application records to Supabase identities:
--
--   students.auth_user_id   -> auth.users(id), UNIQUE (one login = one student)
--   teachers                -> faculty directory, keyed by auth.users(id)
--   faculty_classes.owner_teacher_id -> who may manage the class
--
-- Order: base columns first, then tables, then optional columns with
-- `ADD COLUMN IF NOT EXISTS`, then foreign keys and indexes. Every statement is
-- idempotent, so the file is safe to re-run.
--
-- Table creation uses `CREATE TABLE IF NOT EXISTS` only. Columns on already
-- deployed tables are never dropped or retyped.

-- app-migration:
CREATE TABLE IF NOT EXISTS faculty_classes (
    class_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_name        text NOT NULL UNIQUE,
    program           text NOT NULL,
    semester          integer NOT NULL CHECK (semester >= 1),
    section           text NOT NULL,
    description       text NOT NULL DEFAULT '',
    created_at        timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- app-migration:
CREATE TABLE IF NOT EXISTS teachers (
    teacher_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id      uuid UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
    name              text NOT NULL,
    email             text UNIQUE,
    created_at        timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

