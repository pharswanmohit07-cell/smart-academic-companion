"""
Database entry point.

:func:`get_connection` returns a connection for whichever back end the
configuration selects:

* ``DATABASE_URL`` set -> Supabase PostgreSQL (production, Render)
* otherwise          -> local SQLite file (development, tests)

Both return objects implementing the same small API (``execute``,
``fetchone``/``fetchall`` on cursors, ``commit``, ``rollback``, ``close``),
so routes and modules do not branch on the engine. Credential handling lives
in :mod:`config`; keeping it here means tests can point ``DATABASE_FILE`` at
a temporary file without touching the environment.
"""

