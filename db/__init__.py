def _settings():
    from config import settings

    return settings


def backend_name():
    """Return ``"postgresql"`` or ``"sqlite"`` for the active configuration."""
    return "postgresql" if _settings().DATABASE_URL else "sqlite"


def is_postgres():
    return backend_name() == "postgresql"


def get_connection(dsn=None):
    """Open a connection using the configured back end."""
    settings = _settings()
    if dsn or settings.DATABASE_URL:
        return pg_backend.connect(dsn or settings.DATABASE_URL)
    return sqlite_backend.connect()


def last_insert_id(connection, table, column):
    """Return the id generated for the last INSERT on ``table``.

    PostgreSQL serial columns advance a sequence named ``<table>_<column>_seq``
    (``currval`` returns the value generated by the last INSERT on this
    session's connection, which is what ``lastrowid`` gave us on SQLite).
    """
    if connection.backend == "postgresql":
        row = connection.execute(
            f"SELECT currval(pg_get_serial_sequence(?, ?)) AS id", (table, column)
        ).fetchone()
        return int(row["id"])
    return connection._connection.execute("SELECT last_insert_rowid()").fetchone()[0]


def initialize_database(database_file=None, schema_path=None):
    """Create the local SQLite schema and apply compatibility columns.

    This is for local development and tests only. The PostgreSQL schema is
    created by the migrations in ``migrations/`` (``python manage.py migrate``).
    """
    import database as legacy_schema

    if database_file is None:
        return legacy_schema.initialize_database()

    # A test pointed the schema at a throw-away file: build it through a
    # connection to that file, without touching the configured database.
    from contextlib import closing

    with closing(sqlite_backend.connect_to(database_file)) as connection:
        try:
            connection.executescript(Path(schema_path or legacy_schema.SCHEMA_PATH)
                                     .read_text(encoding="utf-8"))
            legacy_schema._apply_compatibility_migrations(connection)
            legacy_schema._assign_legacy_students_to_classes(connection)
            connection.commit()
        except Exception:
            connection.rollback()
            raise
    return database_file


def migrations_required():
    """Return migration file names that have not been recorded as applied."""
    directory = Path(__file__).resolve().parent.parent / "migrations"
    applied = _applied_migrations()
    return [
        path.name for path in sorted(directory.glob("*.sql"))
        if path.name not in applied
    ]


def _applied_migrations():
    from manage import applied_migrations

    return applied_migrations()
