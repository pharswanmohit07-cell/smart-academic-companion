"""
Operational commands for the Smart Academic Companion.

    python manage.py migrate                apply pending SQL migrations (DATABASE_URL)
    python manage.py migrate --status       show applied / pending migrations
    python manage.py migrate --file X.sql   apply one file (owner role; no ledger)
    python manage.py check-db               connectivity and startup checks
    python manage.py provision-faculty      link a Supabase user as faculty
    python manage.py provision-admin        link a Supabase user as admin
    python manage.py link-student           link a student record to a login
    python manage.py demote                  set a profile back to student

Migrations are applied with the DATABASE_URL connection (the database owner),
which is the only role allowed to change the schema. Each file records its
name in app_migrations and runs inside a transaction, so a failure leaves the
database unchanged and the command can be re-run safely.

Supabase's SQL editor connects as the `postgres` role; if a migration was
applied there instead, re-running it here is still safe: every statement is
idempotent (IF NOT EXISTS / DROP POLICY IF EXISTS / CREATE OR REPLACE).
"""

import argparse
import sys
from contextlib import closing
from pathlib import Path

from db import DatabaseError

MIGRATIONS_DIR = Path(__file__).resolve().parent / "migrations"

LEDGER_SQL = """
CREATE TABLE IF NOT EXISTS app_migrations (
    filename    text PRIMARY KEY,
    applied_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""


def _connection_or_exit(database_url=None):
    from config import settings
    from db import get_connection
    from db.base import DatabaseError

    url = database_url or settings.DATABASE_URL
    if not url:
        raise SystemExit(
            "DATABASE_URL is not set. Export the Supabase connection string "
            "(Session pooler, SSL required) before running this command."
        )
    try:
        return get_connection(url)
    except DatabaseError as exc:
        raise SystemExit(f"Could not connect to PostgreSQL: {exc}")


def applied_migrations(connection=None):
    """Return the migration file names already recorded in the database."""
    from db.base import DatabaseError

    owns_connection = connection is None
    if owns_connection:
        connection = _connection_or_exit()
    try:
        connection.execute(LEDGER_SQL)
        connection.commit()
        rows = connection.execute("SELECT filename FROM app_migrations").fetchall()
        return {row["filename"] for row in rows}
    except DatabaseError:
        connection.rollback()
        return set()
    finally:
        if owns_connection:
            connection.close()


def migration_files():
    return sorted(MIGRATIONS_DIR.glob("*.sql"))


def run_migrations(status_only=False, database_url=None, database_file=None):
    """Apply pending migration files. Returns (applied, skipped).

    ``database_file`` runs the files against a throw-away SQLite database
    (used by the test suite). Files that use PostgreSQL-only DDL are skipped
    there and reported; on PostgreSQL every file is applied.
    """
    from db import sqlite_backend
    from db.base import SchemaMismatchError, split_sql_statements

    if database_file:
        connection = sqlite_backend.connect_to(database_file)
    else:
        connection = _connection_or_exit(database_url)

    applied_now, skipped = [], []
    # SQLite is maintained by database.py. A PostgreSQL migration that uses
    # server-only DDL (DO blocks, identity columns, RLS) must be skipped as a
    # whole *before* any statement runs, otherwise a partly applied file would
    # be recorded in the ledger and never revisited.
    POSTGRES_ONLY = ("DO $", "GENERATED BY DEFAULT AS IDENTITY",
                     "CREATE POLICY", "ALTER POLICY",
                     "ENABLE ROW LEVEL SECURITY", "CREATE OR REPLACE FUNCTION",
                     "REVOKE ", "ADD COLUMN IF NOT EXISTS", "SET search_path",
                     "::regnamespace", "pg_constraint")
    with closing(connection):
        done = applied_migrations(connection)
        for path in migration_files():
            if path.name in done:
                skipped.append(path.name)
                if status_only:
                    print(f"applied  {path.name}")
                continue
            if status_only:
                print(f"pending  {path.name}")
                continue
            statements = split_sql_statements(path.read_text(encoding="utf-8"))
            if connection.backend == "sqlite" and any(
                marker in statement
                for statement in statements
                for marker in POSTGRES_ONLY
            ):
                print(f"skipped  {path.name} (PostgreSQL-only statements)")
                skipped.append(path.name)
                continue
            try:
                for statement in statements:
                    connection.execute(statement)
                connection.execute(
                    "INSERT INTO app_migrations (filename) VALUES (?) "
                    "ON CONFLICT (filename) DO NOTHING",
                    (path.name,),
                )
                connection.commit()
            except (DatabaseError, SchemaMismatchError) as exc:
                connection.rollback()
                if connection.backend == "sqlite":
                    # Local SQLite is maintained by database.py; PostgreSQL-only
                    # statements (DO blocks, ADD COLUMN IF NOT EXISTS, identity
                    # columns) cannot be applied here. Record nothing, so the
                    # file stays pending and is applied on PostgreSQL.
                    print(f"skipped  {path.name} (not a SQLite migration: {exc})")
                    continue
                raise SystemExit(
                    f"Migration {path.name} failed and was rolled back: {exc}"
                ) from exc
            applied_now.append(path.name)
            print(f"applied  {path.name}")
    return applied_now, skipped


def apply_single_file(path):
    from db.base import split_sql_statements

    connection = _connection_or_exit()
    statements = split_sql_statements(Path(path).read_text(encoding="utf-8"))
    with closing(connection):
        try:
            for statement in statements:
                connection.execute(statement)
            connection.commit()
        except DatabaseError as exc:
            connection.rollback()
            raise SystemExit(f"{path} failed and was rolled back: {exc}") from exc
    print(f"applied  {path}")


def check_database():
    """Report what the deployed database looks like. Exit code 1 on failure."""
    from config import settings

    connection = _connection_or_exit()
    problems = []
    with closing(connection):
        print(f"database : {connection.backend}")
        for table in ("students", "faculty_classes", "teachers", "attendance",
                      "marks", "timetable", "subjects", "assessment_items"):
            exists = connection.table_exists(table)
            print(f"table {table:<20} {'ok' if exists else 'MISSING'}")
            if not exists:
                problems.append(f"missing table {table}")
        if connection.table_exists("students"):
            columns = connection.table_columns("students")
            for column in ("auth_user_id", "class_id"):
                if column not in columns:
                    problems.append(f"students.{column} missing")
            if connection.backend == "postgresql":
                rows = connection.execute(
                    "SELECT relname, relrowsecurity FROM pg_class "
                    "WHERE relnamespace = 'public'::regnamespace AND relkind = 'r'"
                ).fetchall()
                without_rls = [row["relname"] for row in rows
                               if not row["relrowsecurity"]]
                if without_rls:
                    print("RLS disabled: " + ", ".join(without_rls))
                    problems.append("row level security missing on some tables")
                else:
                    print("RLS        enabled on every table")

    pending = migrated_pending()
    if pending:
        problems.append("pending migrations: " + ", ".join(pending))

    if problems:
        for problem in problems:
            print(f"problem  : {problem}", file=sys.stderr)
        raise SystemExit(1)

    if settings.IS_PRODUCTION:
        missing = settings.missing_for_production()
        if missing:
            raise SystemExit("Missing environment variables: " + ", ".join(missing))
    print("database check passed")


def migrated_pending():
    connection = _connection_or_exit()
    try:
        done = applied_migrations(connection)
    finally:
        connection.close()
    return [path.name for path in migration_files() if path.name not in done]


def _profile(connection, email):
    row = connection.execute(
        "SELECT user_id, email, role FROM public.user_profiles WHERE lower(email) = lower(?)",
        (email,),
    ).fetchone()
    if row is None:
        raise SystemExit(
            f"No profile found for {email}. Create the account in Supabase Auth first "
            "(dashboard: Authentication > Users > Add user, or let the user sign up), then retry."
        )
    return row


def provision_faculty(email, name=None):
    """Create the teacher row and set the trusted role to 'faculty'."""
    connection = _connection_or_exit()
    with closing(connection):
        profile = _profile(connection, email)
        if profile["role"] == "admin":
            raise SystemExit(f"{email} is an admin; refusing to downgrade to faculty.")
        connection.execute(
            """INSERT INTO teachers (auth_user_id, name, email)
               VALUES (?, ?, ?)
               ON CONFLICT (auth_user_id) DO UPDATE SET name = excluded.name""",
            (profile["user_id"], name or email, email),
        )
        connection.execute(
            "UPDATE public.user_profiles SET role = 'faculty' WHERE user_id = ?",
            (profile["user_id"],),
        )
        connection.commit()
    print(f"faculty: {email} (auth user {profile['user_id']})")


def provision_admin(email):
    """Set the trusted role to 'admin'. Run by an operator with database access."""
    connection = _connection_or_exit()
    with closing(connection):
        profile = _profile(connection, email)
        connection.execute(
            "UPDATE public.user_profiles SET role = 'admin' WHERE user_id = ?",
            (profile["user_id"],),
        )
        connection.commit()
    print(f"admin: {email}")


def demote(email):
    connection = _connection_or_exit()
    with closing(connection):
        profile = _profile(connection, email)
        connection.execute(
            "UPDATE public.user_profiles SET role = 'student' WHERE user_id = ?",
            (profile["user_id"],),
        )
        connection.execute(
            "UPDATE teachers SET auth_user_id = NULL WHERE auth_user_id = ?",
            (profile["user_id"],),
        )
        connection.commit()
    print(f"student: {email}")


def issue_bootstrap():
    """Mint the one-time admin setup code.

    This is the trusted bootstrap: it needs ``DATABASE_URL``, so only someone
    with the database credentials can create it. The code is printed once and
    only its SHA-256 hash is stored; it is consumed by the first registration
    that submits it while the profile table is still empty.
    """
    from app.accounts import AccountError, issue_bootstrap_code

    try:
        code = issue_bootstrap_code()
    except AccountError as exc:
        raise SystemExit(str(exc)) from exc
    print("Admin setup code (shown once, single use):")
    print(f"  {code}")
    print("Register at /auth/signup and paste it into 'Administrator setup code'.")
    print("It is invalidated by rerunning this command and after first use.")


def bootstrap_status():
    connection = _connection_or_exit()
    with closing(connection):
        if connection.backend != "postgresql":
            raise SystemExit("Bootstrap applies to PostgreSQL only.")
        row = connection.execute(
            "SELECT COUNT(*) AS total FROM public.user_profiles"
        ).fetchone()
        profiles = int(row["total"])
        if profiles:
            print(f"profiles: {profiles} -> bootstrap closed (signup creates students)")
            return
        try:
            issued = connection.execute(
                "SELECT created_at FROM admin_bootstrap "
                "WHERE id = 1 AND claimed_at IS NULL"
            ).fetchone()
        except Exception:  # noqa: BLE001 - table does not exist yet
            issued = None
        print("profiles: 0 -> bootstrap closed unless a code is issued")
        print("unused code:", (issued["created_at"] if issued else "none"))


def link_student(email, auth_email=None, create=False):
    """Attach a login (auth.users) to an existing student academic record.

    Matching is by email. ``--create`` inserts a new student row when the email
    has no record yet, so a fresh signup has something to show.
    """
    connection = _connection_or_exit()
    login_email = auth_email or email
    with closing(connection):
        profile = _profile(connection, login_email)
        student = connection.execute(
            "SELECT student_id FROM students WHERE lower(email) = lower(?)", (email,)
        ).fetchone()
        if student is None and create:
            connection.execute(
                """INSERT INTO students (name, email, auth_user_id)
                   VALUES (?, ?, ?)""",
                (profile.get("display_name") or login_email, email, profile["user_id"]),
            )
            connection.commit()
            from db import last_insert_id

            print(f"created student {last_insert_id(connection, 'students', 'student_id')} "
                  f"-> {login_email}")
            return
        if student is None:
            raise SystemExit(f"No student record with email {email}. Use --create to add one.")
        connection.execute(
            "UPDATE students SET auth_user_id = ? WHERE student_id = ?",
            (profile["user_id"], student["student_id"]),
        )
        connection.commit()
    print(f"linked student {student['student_id']} -> {login_email}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    migrate = sub.add_parser("migrate", help="apply pending SQL migrations")
    migrate.add_argument("--status", action="store_true", help="only list migrations")
    migrate.add_argument("--file", help="apply one SQL file without recording it")

    sub.add_parser("check-db", help="verify tables, RLS and pending migrations")

    sub.add_parser(
        "issue-bootstrap",
        help="mint the one-time admin setup code (PostgreSQL only)")

    bootstrap_status = sub.add_parser(
        "bootstrap-status", help="show whether an unused bootstrap code exists")
    bootstrap_status.add_argument("--json", action="store_true")

    faculty = sub.add_parser("provision-faculty", help="grant the faculty role")
    faculty.add_argument("email")
    faculty.add_argument("--name")

    admin = sub.add_parser("provision-admin", help="grant the admin role")
    admin.add_argument("email")

    downgrade = sub.add_parser("demote", help="set a profile back to student")
    downgrade.add_argument("email")

    link = sub.add_parser("link-student", help="link a student record to a login")
    link.add_argument("email", help="email on the student record")
    link.add_argument("--auth-email", help="login email if different")
    link.add_argument("--create", action="store_true", help="create the student record")

    args = parser.parse_args(argv)
    if args.command == "migrate":
        if args.file:
            apply_single_file(args.file)
        else:
            run_migrations(status_only=args.status)
    elif args.command == "check-db":
        check_database()
    elif args.command == "issue-bootstrap":
        issue_bootstrap()
    elif args.command == "bootstrap-status":
        bootstrap_status()
    elif args.command == "provision-faculty":
        provision_faculty(args.email, args.name)
    elif args.command == "provision-admin":
        provision_admin(args.email)
    elif args.command == "demote":
        demote(args.email)
    elif args.command == "link-student":
        link_student(args.email, args.auth_email, args.create)


if __name__ == "__main__":
    main()
